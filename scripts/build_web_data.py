"""Generate the browser files that must stay in sync with the Python reference.

    python scripts/build_web_data.py          # (re)write docs/messages.js and tests/vectors.json
    python scripts/build_web_data.py --check  # exit 1 if either file is stale (used by the tests)

* docs/samples.js    : the two fictional sample invoices, for the page's "load sample" buttons.
* docs/messages.js   : the bilingual message table, copied from etavalidator/messages.py.
* tests/vectors.json : documents plus the findings the Python validator reports for them.
  The JS port (docs/validator.js) must reproduce level, code and path for every vector.
"""
import copy
import json
import os
import sys
from datetime import datetime, timezone

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)

from etavalidator import validate_data  # noqa: E402
from etavalidator.messages import MESSAGES  # noqa: E402

NOW_ISO = "2026-06-01T00:00:00Z"
NOW = datetime(2026, 6, 1, tzinfo=timezone.utc)


def _sample(name):
    with open(os.path.join(ROOT, "sample-data", name), encoding="utf-8") as fh:
        return json.load(fh)


def messages_js():
    body = json.dumps({k: list(v) for k, v in MESSAGES.items()}, ensure_ascii=False, indent=2)
    return ("// GENERATED by scripts/build_web_data.py from etavalidator/messages.py. Do not edit.\n"
            "(function (root, factory) {\n"
            "  if (typeof module === 'object' && module.exports) module.exports = factory();\n"
            "  else root.ETA_MESSAGES = factory();\n"
            "})(typeof self !== 'undefined' ? self : this, function () {\n"
            "  return " + body.replace("\n", "\n  ") + ";\n"
            "});\n")


def samples_js():
    data = {"valid": _sample("valid_invoice.json"), "invalid": _sample("invalid_invoice.json")}
    body = json.dumps(data, ensure_ascii=False, indent=2)
    return ("// GENERATED by scripts/build_web_data.py from sample-data/. Do not edit.\n"
            "window.ETA_SAMPLES = " + body + ";\n")


def _cases():
    base = _sample("valid_invoice.json")
    cases = []

    def add(name, data, tolerance="0.01"):
        cases.append({"name": name, "data": data, "tolerance": tolerance})

    def mut(name, fn, tolerance="0.01"):
        d = copy.deepcopy(base)
        fn(d)
        add(name, d, tolerance)

    add("valid sample", base)
    add("invalid sample", _sample("invalid_invoice.json"))
    mut("missing internalID", lambda d: d.pop("internalID"))
    mut("bad document type", lambda d: d.update(documentType="X"))
    mut("future date", lambda d: d.update(dateTimeIssued="2030-01-01T00:00:00Z"))
    mut("date wrong shape", lambda d: d.update(dateTimeIssued="2026-01-01 10:00"))
    mut("impossible date", lambda d: d.update(dateTimeIssued="2026-13-45T00:00:00Z"))
    mut("no lines", lambda d: d.update(invoiceLines=[]))
    mut("issuer without branch", lambda d: d["issuer"]["address"].pop("branchID"))
    mut("credit note without reference", lambda d: d.update(documentType="C"))
    mut("business receiver without id", lambda d: d["receiver"].pop("id"))
    mut("bad tax id shape", lambda d: d["issuer"].update(id="12345"))
    mut("empty description", lambda d: d["invoiceLines"][0].update(description="  "))
    mut("bad item type", lambda d: d["invoiceLines"][0].update(itemType="ZZZ"))
    mut("string number not numeric", lambda d: d["invoiceLines"][0].update(quantity="abc"))
    mut("negative quantity", lambda d: d["invoiceLines"][0].update(quantity=-1))
    mut("sales total mismatch", lambda d: d["invoiceLines"][0].update(salesTotal=1))
    mut("net total mismatch", lambda d: d["invoiceLines"][0].update(netTotal=1))
    mut("vat amount mismatch", lambda d: d["invoiceLines"][0]["taxableItems"][0].update(amount=1))
    mut("line total mismatch", lambda d: d["invoiceLines"][0].update(total=1))
    mut("header sales mismatch", lambda d: d.update(totalSalesAmount=1))
    mut("header net mismatch", lambda d: d.update(netAmount=1))
    mut("header discount mismatch", lambda d: d.update(totalDiscountAmount=5))
    mut("header tax mismatch", lambda d: d["taxTotals"][0].update(amount=1))
    mut("header tax type missing", lambda d: d.update(taxTotals=[]))
    mut("header total mismatch", lambda d: d.update(totalAmount=1))
    mut("rounding within tolerance",
        lambda d: d.update(totalAmount=float(d["totalAmount"]) + 0.005))
    mut("rounding outside tolerance",
        lambda d: d.update(totalAmount=float(d["totalAmount"]) + 0.5))
    mut("rounding accepted with wider tolerance",
        lambda d: d.update(totalAmount=float(d["totalAmount"]) + 0.5), tolerance="1")

    def foreign(d):
        d["invoiceLines"][0]["unitValue"].update(currencySold="USD")
    mut("foreign currency without rate", foreign)

    def foreign_math(d):
        d["invoiceLines"][0]["unitValue"].update(currencySold="USD", amountSold=10, currencyExchangeRate=50)
    mut("foreign currency math", foreign_math)

    def withholding(d):
        line = d["invoiceLines"][0]
        line["taxableItems"].append({"taxType": "T4", "subType": "W010", "amount": 1, "rate": 1})
    mut("withholding tax added (inconsistent)", withholding)

    def withholding_ok(d):
        line = d["invoiceLines"][1]
        line["taxableItems"].append({"taxType": "T4", "amount": 50.01, "subType": "W010", "rate": 1})
        line["total"] = round(5001 + 700.14 - 50.01, 2)
        d["taxTotals"].append({"taxType": "T4", "amount": 50.01})
        d["totalAmount"] = round(10830 + line["total"], 2)
    mut("withholding tax is subtracted", withholding_ok)

    def items_disc_ok(d):
        d["invoiceLines"][1]["itemsDiscount"] = 10
        d["invoiceLines"][1]["total"] = round(5701.14 - 10, 2)
        d["totalAmount"] = round(10830 + d["invoiceLines"][1]["total"], 2)
    mut("items discount reduces total", items_disc_ok)

    def extra_ok(d):
        d["extraDiscountAmount"] = 100
        d["totalAmount"] = 16431.14
    mut("extra discount consistent", extra_ok)
    mut("foreign currency consistent", lambda d: d["invoiceLines"][0]["unitValue"].update(
        currencySold="USD", amountSold=20, currencyExchangeRate=50))

    def items_disc(d):
        d["invoiceLines"][0]["itemsDiscount"] = 3
    mut("items discount", items_disc)

    def extra_disc(d):
        d["extraDiscountAmount"] = 7
    mut("extra discount", extra_disc)

    def person_receiver(d):
        d["receiver"] = {"type": "P", "address": d["receiver"]["address"]}
    mut("anonymous person receiver", person_receiver)

    def person_big(d):
        d["receiver"] = {"type": "P", "address": d["receiver"]["address"]}
        d["totalAmount"] = 60000
    mut("person receiver above 50k", person_big)

    mut("taxTotals is not a list", lambda d: d.update(taxTotals=5))
    mut("tax type is a list", lambda d: d["invoiceLines"][0]["taxableItems"][0].update(taxType=[]))
    mut("item type is an empty list", lambda d: d["invoiceLines"][0].update(itemType=[]))
    mut("missing address", lambda d: d["receiver"].pop("address"))
    mut("line is not an object", lambda d: d.update(invoiceLines=[5]))
    mut("tax items missing", lambda d: d["invoiceLines"][0].pop("taxableItems"))

    add("batch with duplicate id", [copy.deepcopy(base), copy.deepcopy(base)])
    bad = copy.deepcopy(base)
    bad["internalID"] = "X"
    bad["totalAmount"] = 1
    add("batch paths prefixed", [copy.deepcopy(base), bad])
    add("documents wrapper", {"documents": [copy.deepcopy(base)]})
    no_id = [copy.deepcopy(base), copy.deepcopy(base)]
    for d in no_id:
        d.pop("internalID")
    add("batch without ids", no_id)
    add("scalar input", 5)
    add("empty object", {})
    return cases


def vectors_json():
    out = []
    for c in _cases():
        issues = validate_data(c["data"], tolerance=c["tolerance"], now=NOW)
        out.append({"name": c["name"], "now": NOW_ISO, "tolerance": c["tolerance"], "data": c["data"],
                    "expected": [[i.level, i.code, i.path] for i in issues]})
    return json.dumps(out, ensure_ascii=False, indent=1) + "\n"


TARGETS = {
    os.path.join(ROOT, "docs", "messages.js"): messages_js,
    os.path.join(ROOT, "docs", "samples.js"): samples_js,
    os.path.join(ROOT, "tests", "vectors.json"): vectors_json,
}


def stale():
    bad = []
    for path, make in TARGETS.items():
        try:
            with open(path, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != make():
            bad.append(os.path.relpath(path, ROOT))
    return bad


if __name__ == "__main__":
    if "--check" in sys.argv:
        files = stale()
        if files:
            print("stale: " + ", ".join(files) + " (run python scripts/build_web_data.py)")
            sys.exit(1)
        print("web data is up to date")
    else:
        for path, make in TARGETS.items():
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(make())
            print("wrote", os.path.relpath(path, ROOT))
